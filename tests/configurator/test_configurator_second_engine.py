"""The configurator chooses the panel's second engine (Part 2): AF3 by default, Protenix opt-in.

Pinned here:

* An old config (no `second_engine` key) generates a `run_evaluate.sh` byte-identical to what
  the configurator wrote before the key existed. The literals below were produced by running
  the pre-change configurator (commit 7a5abd0, extracted with `git archive` into a scratch
  directory, never by checking the live tree out) on the same three configs. The only thing
  that varies by machine is the recorded checkout path, so that one line is a placeholder.
* A Protenix slot emits `--second-engine protenix` and never `--skip-af3`; a declined Protenix
  slot emits `--skip-second`.
* The wizard's engine questions for AF3 only / Protenix only / both installed, scripted through
  `input`, and `primary_engine` choices follow the slot.
* The agent-facing invariant says three engines, one of them the second engine.
"""

import builtins
import json
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "configurator"))
import configurator as conf  # noqa: E402

SMOKE = REPO / "examples" / "CALCA" / "smoke.json"
TARGET = REPO / "examples" / "CALCA" / "target.pdb"

# ----------------------------------------------------------------- pre-change literals

HEAD = r"""#!/usr/bin/env bash
# Run Evaluator for T
# Generated by BinderScout Configurator
set -euo pipefail

# -- Locate this run folder and the BinderScout checkout --------------------
# RUN_DIR is where THIS script lives (symlinks resolved), so a moved or copied run
# folder operates on itself instead of on the folder it was generated in.
RUN_DIR="$(cd -P -- "$(dirname -- "$(readlink -f -- "${BASH_SOURCE[0]}")")" && pwd -P)"
# BINDERSCOUT_DIR is the checkout that holds the installed tools: the environment
# wins, otherwise the location recorded when this folder was generated.
_BS_RECORDED_DIR=@RECORDED_DIR@
BINDERSCOUT_DIR="${BINDERSCOUT_DIR:-$_BS_RECORDED_DIR}"
if [[ ! -f "$BINDERSCOUT_DIR/binderscout.py" ]]; then
    echo "ERROR: no BinderScout checkout at $BINDERSCOUT_DIR (the location recorded when this" >&2
    echo "       run folder was generated). Set BINDERSCOUT_DIR to the checkout that holds" >&2
    echo "       the installed tools, then re-run." >&2
    exit 1
fi
export BINDERSCOUT_DIR
# -- end of locate block --

# Robust conda init — works in non-interactive shells (no conda on PATH by default)
set +u
_conda_found=false
for _conda_sh in \
    "${BINDERSCOUT_CONDA:+$BINDERSCOUT_CONDA/etc/profile.d/conda.sh}" \
    "$BINDERSCOUT_DIR/conda/etc/profile.d/conda.sh" \
    "${CONDA_EXE:+${CONDA_EXE%/bin/*}/etc/profile.d/conda.sh}" \
    "${HOME}/miniforge3/etc/profile.d/conda.sh" \
    "${HOME}/mambaforge/etc/profile.d/conda.sh" \
    "${HOME}/miniconda3/etc/profile.d/conda.sh" \
    "${HOME}/anaconda3/etc/profile.d/conda.sh" \
    "/opt/conda/etc/profile.d/conda.sh" \
    "/opt/miniforge3/etc/profile.d/conda.sh"; do
    # shellcheck disable=SC1090
    [[ -f "$_conda_sh" ]] && { source "$_conda_sh"; _conda_found=true; break; }
done
[[ "$_conda_found" == true ]] || { echo "ERROR: conda not found — install Miniconda or Miniforge first." >&2; exit 1; }
set -u

EVAL_SCRIPT="$BINDERSCOUT_DIR/Evaluator/evaluate.sh"
OUTPUT_DIR="$RUN_DIR/evaluate"

if [[ ! -f "$EVAL_SCRIPT" ]]; then
    echo "ERROR: Evaluator not found at $EVAL_SCRIPT" >&2
    echo "Run: binderscout install --tool evaluator" >&2
    exit 1
fi

# Step 1: Extract sequences from design tool outputs into FASTA
SEQUENCES="$OUTPUT_DIR/sequences.fasta"

# Collect design sequences from enabled tools
if [[ ! -f "$SEQUENCES" ]]; then
    echo "  Extracting sequences from design outputs..."
    conda run -n binder-eval binder-compare extract \
        --bindcraft "$RUN_DIR/bindcraft/outputs" \
        --target-seq "AAAAA" \
        --output "$SEQUENCES" \
        --collect-structures "$OUTPUT_DIR/design_structures" \
        ${BINDERSCOUT_ALLOW_EMPTY:+--allow-empty}
fi

"""

TAIL_AF3_ALL_ON = r"""# Step 2: Run evaluation pipeline
echo "=== Running Evaluator for T ==="
bash "$EVAL_SCRIPT" \
    --sequences "$SEQUENCES" \
    --target-seq "AAAAA" \
    --output "$OUTPUT_DIR" \
    --tool-root "$RUN_DIR" \
    --skip-soluprot \
    --skip-tmprot \
    --primary-engine boltz \
    --min-engines 2 \
    --resume

"""

TAIL_AF3_OFF = r"""# Step 2: Run evaluation pipeline
echo "=== Running Evaluator for T ==="
bash "$EVAL_SCRIPT" \
    --sequences "$SEQUENCES" \
    --target-seq "AAAAA" \
    --output "$OUTPUT_DIR" \
    --tool-root "$RUN_DIR" \
    --skip-af3 \
    --skip-soluprot \
    --skip-tmprot \
    --primary-engine esmfold2 \
    --min-engines 2 \
    --resume

"""

TAIL_OLD_MINIMAL = r"""# Step 2: Run evaluation pipeline
echo "=== Running Evaluator for T ==="
bash "$EVAL_SCRIPT" \
    --sequences "$SEQUENCES" \
    --target-seq "AAAAA" \
    --output "$OUTPUT_DIR" \
    --tool-root "$RUN_DIR" \
    --skip-af3 \
    --skip-esmfold2 \
    --skip-soluprot \
    --skip-tmprot \
    --primary-engine boltz \
    --resume

"""

_BASE = {
    "name": "T",
    "min_length": 20,
    "max_length": 30,
    "n_designs": 1,
    "chains": "A",
    "hotspots": None,
    "target_sequence": "AAAAA",
}


def _script(tmp_path, **over):
    cfg = {**_BASE, "run_dir": tmp_path, **over}
    path = tmp_path / "run_evaluate.sh"
    conf.write_run_evaluate(path, cfg, {"evaluator": True, "bindcraft": True})
    return path.read_text()


def _expected(tail):
    return HEAD.replace("@RECORDED_DIR@", str(conf.BINDERSCOUT_DIR)) + tail


@pytest.mark.parametrize(
    ("over", "tail"),
    [
        (
            {"use_boltz": True, "use_af3": True, "use_esmfold2": True, "primary_engine": "boltz", "min_engines": 2},
            TAIL_AF3_ALL_ON,
        ),
        (
            {"use_boltz": True, "use_af3": False, "use_esmfold2": True, "primary_engine": "esmfold2", "min_engines": 2},
            TAIL_AF3_OFF,
        ),
        ({}, TAIL_OLD_MINIMAL),
    ],
    ids=["af3-on", "af3-off", "old-config-without-any-engine-key"],
)
def test_an_af3_config_generates_the_pre_change_script_byte_for_byte(tmp_path, over, tail):
    assert _script(tmp_path, **over) == _expected(tail)


def test_an_explicit_af3_slot_is_still_byte_identical(tmp_path):
    """`second_engine: af3` is what an old config means, so naming it must not change a byte."""
    over = {"use_boltz": True, "use_af3": True, "use_esmfold2": True, "primary_engine": "boltz", "min_engines": 2}
    assert _script(tmp_path, second_engine="af3", **over) == _expected(TAIL_AF3_ALL_ON)


# ------------------------------------------------------------------ the Protenix slot


def test_a_protenix_slot_emits_second_engine_and_no_skip_af3(tmp_path):
    body = _script(
        tmp_path,
        second_engine="protenix",
        use_boltz=True,
        use_esmfold2=True,
        primary_engine="boltz",
        min_engines=None,
    )
    assert "    --second-engine protenix \\\n" in body
    assert "--skip-af3" not in body
    assert "--skip-second" not in body
    assert "--skip-boltz2" not in body and "--skip-esmfold2" not in body
    # Stable position: where --skip-af3 sits for an AF3 config.
    assert body.index("--tool-root") < body.index("--second-engine") < body.index("--skip-soluprot")


def test_a_declined_protenix_slot_emits_skip_second(tmp_path):
    body = _script(tmp_path, second_engine="protenix", use_protenix=False, use_boltz=True, use_esmfold2=True)
    assert "    --second-engine protenix \\\n    --skip-second \\\n" in body
    assert "--skip-af3" not in body


def test_a_protenix_primary_is_passed_through(tmp_path):
    body = _script(tmp_path, second_engine="protenix", primary_engine="protenix", use_boltz=True, use_esmfold2=True)
    assert "    --primary-engine protenix \\\n" in body


@pytest.mark.parametrize(
    ("over", "needle"),
    [
        ({"second_engine": "protenix", "use_af3": True}, "exactly one second engine"),
        ({"second_engine": "af3", "use_protenix": True}, "set second_engine to 'protenix'"),
        ({"second_engine": "af2"}, "second_engine must be one of af3, protenix"),
        ({"second_engine": "protenix", "primary_engine": "af3"}, "not in this panel"),
        ({"second_engine": "af3", "use_af3": True, "primary_engine": "protenix"}, "not in this panel"),
    ],
)
def test_an_incoherent_panel_is_refused_not_resolved(tmp_path, capsys, over, needle):
    with pytest.raises(SystemExit) as exc:
        _script(tmp_path, **over)
    assert exc.value.code == 1
    assert needle in capsys.readouterr().out


def test_second_engine_is_a_key_the_validator_accepts():
    known = conf.known_cfg_keys()
    assert {"second_engine", "use_protenix"} <= known


def _config(tmp_path: Path, cfg_over: dict) -> Path:
    payload = json.loads(SMOKE.read_text())
    payload["cfg"].update({"target_pdb_src": str(TARGET), "name": "r", "run_dir": "runs/r", **cfg_over})
    payload["tools_enabled"] = {"mosaic": True, "evaluator": True}
    path = tmp_path / "r.json"
    path.write_text(json.dumps(payload))
    return path


def test_headless_replay_of_a_protenix_config(tmp_path, fake_checkout, replay):
    proc = replay(_config(tmp_path, {"second_engine": "protenix", "use_af3": False}), fake_checkout, tmp_path)
    assert proc.returncode == 0, (proc.stdout + proc.stderr)[-2000:]
    run = fake_checkout / "runs" / "r"
    body = (run / "run_evaluate.sh").read_text()
    assert "--second-engine protenix" in body and "--skip-af3" not in body
    assert "second engine: Protenix" in proc.stdout
    # The choice is recorded in the regenerated config, so the run folder replays to the same panel.
    assert json.loads((run / "config.json").read_text())["cfg"]["second_engine"] == "protenix"


def test_headless_replay_of_an_old_config_keeps_the_af3_slot(tmp_path, fake_checkout, replay):
    proc = replay(_config(tmp_path, {}), fake_checkout, tmp_path)
    assert proc.returncode == 0, (proc.stdout + proc.stderr)[-2000:]
    body = (fake_checkout / "runs" / "r" / "run_evaluate.sh").read_text()
    assert "--second-engine" not in body and "--skip-second" not in body
    assert "second engine: Protenix" not in proc.stdout


# ------------------------------------------------------------------ the wizard matrix


@pytest.fixture
def scripted(monkeypatch, capsys):
    """scripted([answers]) -> prompts shown; each answer is consumed by one input() call."""

    def _go(answers, installed):
        feed = iter(answers)
        prompts: list[str] = []

        def fake_input(prompt=""):
            prompts.append(prompt)
            try:
                return next(feed)
            except StopIteration:
                raise AssertionError(f"unexpected extra prompt: {prompt!r}") from None

        monkeypatch.setattr(builtins, "input", fake_input)
        result = conf.ask_refold_engines(installed)
        assert list(feed) == [], "the wizard asked fewer questions than scripted"
        return result, prompts, capsys.readouterr().out

    return _go


ALL = {"mosaic": True, "esmfold2": True}


def test_af3_only_asks_exactly_what_it_always_asked(scripted):
    result, prompts, out = scripted(["", "", "", ""], {**ALL, "af3": True})
    assert len(prompts) == 4  # Boltz-2, AF3, ESMFold2, primary engine
    assert "Use Boltz-2 (Mosaic venv)?" in prompts[0]
    assert "Use AlphaFold 3 v3.0.2 (binder-eval-af3 env)?" in prompts[1]
    assert "Use ESMFold2 (binder-eval-esmfold2 env)?" in prompts[2]
    assert "Protenix" not in out and all("Protenix" not in p for p in prompts)
    assert result == {
        "use_evaluator": True,
        "use_boltz": True,
        "use_af3": True,
        "use_protenix": False,
        "use_esmfold2": True,
        "second_engine": "af3",
        "primary_engine": "boltz",
        "min_engines": None,
    }


def test_af3_only_two_engine_gate_offer_names_the_missing_engine(scripted):
    result, _prompts, out = scripted(["", "n", "", "", ""], {**ALL, "af3": True})
    assert "Only 2 refold engines selected" in out
    assert "Not selected: AF3." in out
    assert result["min_engines"] == 2 and result["use_af3"] is False and result["second_engine"] == "af3"


def test_protenix_only_offers_it_by_default_with_one_notice(scripted):
    result, prompts, out = scripted(["", "", "", ""], {**ALL, "protenix": True})
    assert "Use Protenix (binder-eval-protenix env)?" in prompts[1]
    assert "AlphaFold" not in "".join(prompts)
    assert out.count("AF3 is not installed") == 1
    assert "Boltz-2 + Protenix + ESMFold2" in out and "not comparable with AF3-panel scores" in out
    assert result["second_engine"] == "protenix"
    assert result["use_protenix"] is True and result["use_af3"] is False
    assert result["primary_engine"] == "boltz"


def test_primary_choices_follow_the_protenix_slot(scripted):
    _result, _prompts, out = scripted(["", "", "", ""], {**ALL, "protenix": True})
    menu = out[out.index("Primary engine for ranking") :]
    assert "boltz" in menu and "protenix" in menu and "esmfold2" in menu
    assert "af3" not in menu


def test_primary_choices_follow_the_af3_slot(scripted):
    _result, _prompts, out = scripted(["", "", "", ""], {**ALL, "af3": True})
    menu = out[out.index("Primary engine for ranking") :]
    assert "af3" in menu and "protenix" not in menu


def test_protenix_can_be_picked_as_primary(scripted):
    result, _prompts, _out = scripted(["", "", "", "2"], {**ALL, "protenix": True})
    assert result["primary_engine"] == "protenix"


def test_declining_protenix_keeps_the_slot_named_and_off(scripted):
    result, _prompts, out = scripted(["", "n", "", "", ""], {**ALL, "protenix": True})
    assert result["second_engine"] == "protenix" and result["use_protenix"] is False
    assert "Not selected: Protenix." in out
    assert result["min_engines"] == 2


def test_both_installed_asks_which_and_defaults_to_af3(scripted):
    result, prompts, out = scripted(["", "", "", ""], {**ALL, "af3": True, "protenix": True})
    assert "Second refold engine (one slot, never both)" in out
    assert len(prompts) == 4  # Boltz-2, the slot, ESMFold2, primary -- never two yes/no for the slot
    assert result["second_engine"] == "af3" and result["use_af3"] is True and result["use_protenix"] is False
    assert "protenix" not in out[out.index("Primary engine for ranking") :]


def test_both_installed_protenix_is_selectable_and_never_both(scripted):
    result, _prompts, out = scripted(["", "2", "", ""], {**ALL, "af3": True, "protenix": True})
    assert result["second_engine"] == "protenix" and result["use_protenix"] is True
    assert result["use_af3"] is False
    assert "af3" not in out[out.index("Primary engine for ranking") :]


def test_both_installed_can_leave_the_slot_empty(scripted):
    result, _prompts, out = scripted(["", "3", "", "", ""], {**ALL, "af3": True, "protenix": True})
    assert result["use_af3"] is False and result["use_protenix"] is False and result["second_engine"] == "af3"
    assert "Not selected: AF3." in out


def test_neither_installed_is_what_it_always_was(scripted):
    result, prompts, out = scripted([""], {"mosaic": True})
    assert "AF3" in out and "requires binder-eval-af3 env" in out
    assert len(prompts) == 1  # Boltz-2 only; ESMFold2 skipped; one engine so no primary menu
    assert result["second_engine"] == "af3" and result["use_af3"] is False
    assert "Enable AF3 or ESMFold2 as a second engine" in out


def test_one_engine_hint_names_the_slot(scripted):
    _result, _prompts, out = scripted(["", "n", "n"], {**ALL, "protenix": True})
    assert "Enable Protenix or ESMFold2 as a second engine" in out


